/**
 * Parse a level's string data into numeric tile array
 * Also extracts spawn/exit positions
 */
export function parseLevel(levelIndex) {
    const level = LEVELS[levelIndex];
    const rows = level.data;
    const height = rows.length;
    const width = rows[0].length;
    const tiles = [];
    let spawn = { x: 3, y: height - 4 };
    let exit = { x: 10, y: 2 };
    const checkpoints = [];
    const spikes = [];
    const strawberries = [];
    const crumbling = [];

    for (let row = 0; row < height; row++) {
        const tileRow = [];
        for (let col = 0; col < width; col++) {
            const ch = rows[row][col];
            if (ch === 'S') {
                spawn = { x: col, y: row };
                tileRow.push(0);
            } else if (ch === '*') {
                strawberries.push({ x: col, y: row });
                tileRow.push(0);
            } else if (ch === 'B') {
                crumbling.push({ x: col, y: row });
                tileRow.push(0);
            } else if (ch === 'E') {
                exit = { x: col, y: row };
                tileRow.push(8);
            } else if (ch === 'C') {
                checkpoints.push({ x: col, y: row });
                tileRow.push(9);
            } else if (ch === '^' || ch === 'v' || ch === '<' || ch === '>') {
                const tileId = TILE_MAP[ch];
                spikes.push({ x: col, y: row, dir: ch, tileId });
                tileRow.push(tileId);
            } else {
                tileRow.push(TILE_MAP[ch] || 0);
            }
        }
        tiles.push(tileRow);
    }

    return {
        tiles, width, height, spawn, exit,
        checkpoints, spikes, strawberries, crumbling,
        theme: level.theme, name: level.name
    };
}
